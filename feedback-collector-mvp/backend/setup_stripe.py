#!/usr/bin/env python3
"""
Stripe Setup Helper for Feedback360
Creates products and prices in your Stripe account
"""
import os
import stripe
from dotenv import load_dotenv

def setup_stripe_products():
    """Create Stripe products and prices for Feedback360"""
    load_dotenv()
    
    api_key = os.getenv("STRIPE_SECRET_KEY")
    if not api_key:
        print("❌ STRIPE_SECRET_KEY not found in .env file")
        print("   1. Create a Stripe account at: https://dashboard.stripe.com")
        print("   2. Get your test API key from: https://dashboard.stripe.com/test/apikeys")
        print("   3. Add it to your .env file: STRIPE_SECRET_KEY=sk_test_...")
        return False
    
    if api_key.startswith("sk_test_51QGjZdGt9vZpMqGgabcdef"):
        print("❌ Please replace the placeholder API key with your actual Stripe key")
        return False
    
    stripe.api_key = api_key
    
    try:
        print("🚀 Setting up Feedback360 products in Stripe...")
        
        # Create Growth product
        growth_product = stripe.Product.create(
            name="Feedback360 Growth",
            description="Limited free-text feedback responses with enhanced features",
            metadata={
                "tier": "growth",
                "app": "feedback360"
            }
        )
        print(f"✅ Created Growth product: {growth_product.id}")
        
        # Create Growth price (£4.99/month)
        growth_price = stripe.Price.create(
            product=growth_product.id,
            currency="gbp",
            unit_amount=499,  # £4.99 in pence
            recurring={
                "interval": "month",
                "interval_count": 1,
                "trial_period_days": 7  # 7-day free trial
            },
            metadata={
                "tier": "growth"
            }
        )
        print(f"✅ Created Growth price: {growth_price.id} (£4.99/month)")
        
        # Create Pro product
        pro_product = stripe.Product.create(
            name="Feedback360 Pro",
            description="Unlimited free-text feedback responses with complete insights",
            metadata={
                "tier": "pro",
                "app": "feedback360"
            }
        )
        print(f"✅ Created Pro product: {pro_product.id}")
        
        # Create Pro price (£9.99/month)
        pro_price = stripe.Price.create(
            product=pro_product.id,
            currency="gbp",
            unit_amount=999,  # £9.99 in pence
            recurring={
                "interval": "month",
                "interval_count": 1,
                "trial_period_days": 14  # 14-day free trial
            },
            metadata={
                "tier": "pro"
            }
        )
        print(f"✅ Created Pro price: {pro_price.id} (£9.99/month)")
        
        # Update .env file
        env_updates = f"""

# Updated Stripe Configuration (Generated by setup_stripe.py)
PRICE_ID_GROWTH={growth_price.id}
PRICE_ID_PRO={pro_price.id}
PRODUCT_ID_GROWTH={growth_product.id}
PRODUCT_ID_PRO={pro_product.id}
"""
        
        with open(".env", "a") as f:
            f.write(env_updates)
        
        print("\n🎉 Stripe setup complete!")
        print(f"📝 Updated .env file with new price IDs")
        print(f"\n📋 Next steps:")
        print(f"   1. Set up webhooks at: https://dashboard.stripe.com/test/webhooks")
        print(f"   2. Add endpoint: http://localhost:8000/api/stripe/webhook")
        print(f"   3. Select events: checkout.session.completed, customer.subscription.*")
        print(f"   4. Copy webhook secret to .env: STRIPE_WEBHOOK_SECRET=whsec_...")
        
        return True
        
    except stripe.error.AuthenticationError:
        print("❌ Invalid Stripe API key. Please check your STRIPE_SECRET_KEY")
        return False
    except Exception as e:
        print(f"❌ Error setting up Stripe: {e}")
        return False

if __name__ == "__main__":
    setup_stripe_products()